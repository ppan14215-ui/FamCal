/**
 * Builds supabase/functions/assistent-eval/index.ts from the real assistent
 * (Julian 30.10.: "Wenn wir so weiter machen und immer wieder Fehler haben
 * wird das nicht mit der App"). Same prompt, same tools, same parsing; only
 * the door is different: a secret token instead of a signed-in family
 * (only its hash is in the code), no family quota, and a choice of model,
 * so Haiku and Sonnet can be compared on the same test list. A new prompt goes here first and reaches the app
 * only after scripts/eval-assistent passes.
 *
 *   node scripts/make-assistent-eval.js   (keeps the token of the last build)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'supabase/functions/assistent/index.ts'), 'utf8');

/** Each swap must match exactly once, so a changed assistent fails loudly instead of building a wrong copy. */
function swap(text, from, to) {
  const n = text.split(from).length - 1;
  if (n !== 1) throw new Error(`make-assistent-eval: expected one match, found ${n}:\n${from}`);
  return text.replace(from, to);
}

// A new token (lost or leaked): make one on the testing machine, keep it in its .env, and pass only
// EVAL_HASH=<its sha256> (or EVAL_TOKEN=<token> where it lives) to this script; then deploy assistent-eval.
const prev = (() => { try { return fs.readFileSync(path.join(root, 'supabase/functions/assistent-eval/index.ts'), 'utf8').match(/EVAL_HASH = '([0-9a-f]{64})'/)?.[1]; } catch { return undefined; } })();
const hash = process.env.EVAL_TOKEN ? require('crypto').createHash('sha256').update(process.env.EVAL_TOKEN).digest('hex') : /^[0-9a-f]{64}$/.test(process.env.EVAL_HASH ?? '') ? process.env.EVAL_HASH : prev;
if (!hash) throw new Error('make-assistent-eval: EVAL_TOKEN fehlt');

let out = src;
out = swap(out, '/**\n * Assistent (', '/**\n * GENERATED by scripts/make-assistent-eval.js from assistent/index.ts. Do not edit.\n * Test door for scripts/eval-assistent: x-eval-token header, no quota, model by variant.\n *\n * Assistent (');
out = swap(out,
  `  // Counted as the signed-in person, so nobody can spend someone else's quota.
  const db = createClient(Deno.env.get('SUPABASE_URL')!, Deno.env.get('SUPABASE_ANON_KEY') ?? req.headers.get('apikey') ?? '', {
    global: { headers: { Authorization: req.headers.get('Authorization') ?? '' } },
  });
  const { data: allowed, error: countError } = await db.rpc('use_ai_call');
  if (countError) return json({ error: 'not_signed_in' }, 401);
  if (!allowed.ok) return json({ error: 'limit', reason: allowed.reason, tier: allowed.tier }, 429);
`,
  `  // Only the test runner knows the token; the code holds just its SHA-256, so reading it gives nothing away.
  const given = new TextEncoder().encode(req.headers.get('x-eval-token') ?? '');
  const hash = [...new Uint8Array(await crypto.subtle.digest('SHA-256', given))].map((b) => b.toString(16).padStart(2, '0')).join('');
  let diff = 0;
  for (let i = 0; i < EVAL_HASH.length; i++) diff |= EVAL_HASH.charCodeAt(i) ^ hash.charCodeAt(i);
  if (diff || given.length < 32) return json({ error: 'forbidden' }, 403);
  const allowed = { left: null as number | null };
  const variant = VARIANTS[req.headers.get('x-eval-variant') ?? 'haiku'];
  if (!variant) return json({ error: 'bad_variant' }, 400);
`);
out = swap(out,
  `const client = new Anthropic({ apiKey: Deno.env.get('ANTHROPIC_API_KEY') });`,
  `const client = new Anthropic({ apiKey: Deno.env.get('ANTHROPIC_API_KEY') });

const EVAL_HASH = '${hash}';
// With thinking on, forced tool use is refused (and Sonnet 5.5 refuses disabled thinking), so those get auto.
const VARIANTS: Record<string, { model: string; tool_choice: { type: 'any' | 'auto' }; thinking: Record<string, string> }> = {
  haiku: { model: 'claude-haiku-5-5', tool_choice: { type: 'any' }, thinking: { type: 'disabled' } },
  'haiku-denkt': { model: 'claude-haiku-5-5', tool_choice: { type: 'auto' }, thinking: { type: 'adaptive' } },
  sonnet: { model: 'claude-sonnet-5-5', tool_choice: { type: 'auto' }, thinking: { type: 'adaptive' } },
};`);
out = swap(out, `    model: 'claude-haiku-5-5',\n`, `    model: variant.model,\n`);
out = swap(out, `    tool_choice: { type: 'any' },\n`, `    tool_choice: variant.tool_choice,\n`);
out = swap(out, `    thinking: { type: 'disabled' },\n`, `    thinking: variant.thinking as never,\n`);
out = swap(out, `import { createClient } from 'npm:@supabase/supabase-js@2';\n`, '');
// The log says which model answered, still never what was said.
out = swap(out, `JSON.stringify({ ms: Date.now() - t0,`, `JSON.stringify({ eval: variant.model, ms: Date.now() - t0,`);

const dir = path.join(root, 'supabase/functions/assistent-eval');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'index.ts'), out);
console.log('supabase/functions/assistent-eval/index.ts geschrieben');
