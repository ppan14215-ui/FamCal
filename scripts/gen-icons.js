// Writes src/lib/clayIcons.ts with a static require() for every clay icon in
// assets/icons (Metro needs literal require paths). Run after adding icons:
//   node scripts/gen-icons.js
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'icons');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.webp')).sort();
const lines = files.map((f) => {
  const key = f.replace(/^icon-/, '').replace(/\.webp$/, '');
  return `  '${key}': require('../../assets/icons/${f}'),`;
});
const out = `// Generated by scripts/gen-icons.js. Do not edit by hand.
/* eslint-disable */
export const clayIcons = {
${lines.join('\n')}
} as const;

export type ClayName = keyof typeof clayIcons;
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'clayIcons.ts'), out);
console.log(files.length, 'icons');
