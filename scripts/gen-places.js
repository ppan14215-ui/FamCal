/**
 * Builds src/data/places.ts: every German municipality with its Bundesland
 * and population, from the official Gemeindeverzeichnis (Destatis GV100,
 * npm package "gemeindeverzeichnis"). Used to fill the Bundesland from the
 * city typed in onboarding (Julian 26.10.: "Fürth, dann Bayern").
 * Run: node scripts/gen-places.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.dirname(require.resolve('gemeindeverzeichnis/package.json'));
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8').trim().split('\n').map((l) => JSON.parse(l));

const laender = read('laender.ndjson').map((l) => l.name);
const byKey = Object.fromEntries(read('laender.ndjson').map((l, i) => [l.schlüssel.land, i]));
const seen = new Map();
for (const g of read('gemeinden.ndjson')) {
  // "Frankfurt am Main, Stadt" -> "Frankfurt am Main"
  const name = g.name.split(',')[0].trim();
  const land = byKey[g.schlüssel.land];
  const key = `${name}|${land}`;
  const pop = g.bevölkerung || 0;
  if (!seen.has(key) || seen.get(key) < pop) seen.set(key, pop);
}
const rows = [...seen.entries()]
  .map(([k, pop]) => { const [n, l] = k.split('|'); return [n, +l, Math.round(pop / 100)]; })
  .sort((a, b) => b[2] - a[2]);

const stand = read('gemeinden.ndjson')[0].stand.slice(0, 10);
const out = `/* Generated by scripts/gen-places.js from the Destatis Gemeindeverzeichnis (Stand ${stand}). Do not edit. */
export const LAENDER = ${JSON.stringify(laender)};
/** name;Land index;population in hundreds, most populous first. */
export const PLACES = ${JSON.stringify(rows.map((r) => r.join(';')).join('\n'))};
`;
fs.writeFileSync(path.join(__dirname, '../src/data/places.ts'), out);
console.log(`${rows.length} places, ${(out.length / 1024).toFixed(0)} KB`);
